const title = required<HTMLElement>("reference-title");
const documentElement = required<HTMLElement>("reference-document");

function required<T extends HTMLElement>(id: string): T {
  const found = document.getElementById(id);
  if (!found) throw new Error(`Missing reference element #${id}`);
  return found as T;
}

function abbreviated(hash: string): string {
  return `${hash.slice(0, 12)}…${hash.slice(-8)}`;
}

function glossary(): string {
  const groups = ["Shared", "Posets", "Steiner categories"] as const;
  return groups
    .map(
      (domain) => `<section class="reference-section"><h2>${domain}</h2><dl class="glossary-list">${definitions
        .filter((definition) => definition.domain === domain)
        .map(
          (definition) => `<div id="${definition.id}"><dt>${definition.term}</dt><dd>${definition.text}</dd></div>`,
        )
        .join("")}</dl></section>`,
    )
    .join("");
}

