async function posetCompleteness(): Promise<string> {
  const manifest = await load<PosetSourceManifest>("data/finite-posets/manifest.json");
  const counts = new Map<number, number>();
  for (const bucket of manifest.label_buckets) {
    counts.set(bucket.order, (counts.get(bucket.order) ?? 0) + bucket.row_count);
  }
  return `<section class="reference-section reference-claim"><p class="eyebrow">Certified coverage</p><h2>All finite Posets through ${manifest.maximum_order} points</h2><p class="reference-lede">Exactly ${manifest.poset_count.toLocaleString()} isomorphism classes. Labeled copies are not included.</p></section>
    <section class="reference-section"><h2>What is complete</h2><ul><li>The isomorphism census for every order 0 through ${manifest.maximum_order}.</li><li>Canonical label, cover relation, elementary order invariants, natural automorphism group, opposite, and minimal beat-point core for every object.</li><li>The linked order complex and exact integral homology for every object.</li><li>The core catalogue and fiber counts relative to this complete bounded universe.</li></ul>
    <p>An absent LMFDB abstract-group label means that the external identification is not attached; it does not make the Poset census or its natural automorphism action incomplete.</p></section>
    <section class="reference-section"><h2>Counts by order</h2><table class="reference-table"><thead><tr><th>Points</th><th>Isomorphism classes</th></tr></thead><tbody>${[...counts]
      .sort(([a], [b]) => a - b)
      .map(([order, count]) => `<tr><td>${order}</td><td>${count.toLocaleString()}</td></tr>`)
      .join("")}</tbody><tfoot><tr><th>Total</th><th>${manifest.poset_count.toLocaleString()}</th></tr></tfoot></table></section>`;
}

