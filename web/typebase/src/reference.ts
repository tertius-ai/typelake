async function load<T>(path: string): Promise<T> {
  const response = await fetch(new URL(path, document.baseURI));
  if (!response.ok) throw new Error(`Reference data returned HTTP ${response.status}`);
  return (await response.json()) as T;
}

async function render(): Promise<void> {
  const path = window.location.pathname.replace(/\/+$/, "");
  let heading = "Glossary";
  let content: string;
  if (path === "/Posets/Source") {
    heading = "Source of the Poset data";
    content = await posetSource();
  } else if (path === "/Posets/Completeness") {
    heading = "Completeness of the Poset data";
    content = await posetCompleteness();
  } else if (path === "/Steiner/Source") {
    heading = "Source of the Steiner-category data";
    content = await steinerSource();
  } else if (path === "/Steiner/Completeness") {
    heading = "Completeness of the Steiner-category data";
    content = await steinerCompleteness();
  } else {
    content = glossary();
  }
  title.textContent = heading;
  document.title = `${heading} — TypeBase Volume I`;
  documentElement.innerHTML = content;
  const target = window.location.hash ? document.querySelector(window.location.hash) : null;
  target?.scrollIntoView({ block: "start" });
}

initializePresentation();
mountPresentationControls();
void render().catch((error) => {
  documentElement.innerHTML = `<p>Unable to open this reference: ${error instanceof Error ? error.message : String(error)}</p>`;
});
